<?php

declare(strict_types=1);

namespace App\Infrastructure\ValueObject\String;

use App\Application\AppUrl;

final readonly class RelativeUrl
{
    private function __construct(
        private string $path,
        private AppUrl $appUrl,
    ) {
    }

    public static function from(string $path, AppUrl $appUrl): self
    {
        return new self(
            path: $path,
            appUrl: $appUrl
        );
    }

    public function toRelativeUrl(): string
    {
        $path = '/'.ltrim($this->path, '/');
        if (null === $this->appUrl->getBasePath()) {
            return $path;
        }

        $basePath = '/'.trim($this->appUrl->getBasePath(), '/');
        // Paths generated by the router already start with the base path when the app knows it
        // runs under it (multi-user installations with an address per path), don't add it twice.
        if ($path === $basePath || str_starts_with($path, $basePath.'/')) {
            return $path;
        }

        return $basePath.$path;
    }
}
