<?php

namespace App\Tests\Infrastructure\ValueObject\String;

use App\Application\AppUrl;
use App\Infrastructure\ValueObject\String\RelativeUrl;
use PHPUnit\Framework\Attributes\DataProvider;
use PHPUnit\Framework\TestCase;

class RelativeUrlTest extends TestCase
{
    #[DataProvider('provideRelativeUrls')]
    public function testToRelativeUrl(string $appUrl, string $path, string $expected): void
    {
        $this->assertSame($expected, RelativeUrl::from($path, AppUrl::fromString($appUrl))->toRelativeUrl());
    }

    public static function provideRelativeUrls(): iterable
    {
        yield 'no base path' => ['https://dreeve.example.com', 'activities', '/activities'];
        yield 'no base path, leading slash' => ['https://dreeve.example.com', '/activities', '/activities'];
        yield 'base path is added' => ['https://dreeve.example.com/alice', 'activities', '/alice/activities'];
        yield 'base path is added to the root' => ['https://dreeve.example.com/alice', '/', '/alice/'];
        // Paths generated by the router of a user that lives under a path already carry it.
        yield 'base path is not added twice' => ['https://dreeve.example.com/alice', '/alice/activities', '/alice/activities'];
        yield 'base path itself is not prefixed' => ['https://dreeve.example.com/alice', '/alice', '/alice'];
        yield 'a path that merely starts with the same letters still gets it' => ['https://dreeve.example.com/alice', '/alicex/activities', '/alice/alicex/activities'];
    }
}
